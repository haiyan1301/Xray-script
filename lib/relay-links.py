#!/usr/bin/env python3
"""Import supported Xray-script relay URIs without executing or fetching them.

The CLI reads one URI from stdin and emits a node without an id. --validate-node
checks a saved imported node and emits the same node. Errors never echo input.
Only standalone transports generated by core/share.sh are accepted. Xray still
validates the final configuration before it is committed.
"""

import argparse
import base64
import binascii
import ipaddress
import json
import re
import sys
import unicodedata
import urllib.parse
import uuid

MAX_INPUT = 65536
OBFS_FIELDS = {
    "xPaddingObfsMode", "xPaddingKey", "xPaddingHeader", "xPaddingPlacement",
    "xPaddingMethod", "uplinkHTTPMethod", "sessionIDPlacement", "sessionKey",
    "seqPlacement", "seqKey",
}
FINGERPRINTS = {
    "chrome", "firefox", "safari", "ios", "android", "edge", "360", "qq",
    "random", "randomized", "randomizedalpn", "randomizednoalpn", "unsafe",
}


class InvalidLink(ValueError):
    pass


def require(condition):
    if not condition:
        raise InvalidLink()


def clean_string(value, minimum=0, maximum=4096):
    require(isinstance(value, str) and minimum <= len(value) <= maximum)
    require(not any(unicodedata.category(c).startswith("C") for c in value))
    return value


def keys(value, allowed, required=()):
    require(isinstance(value, dict) and set(value) <= set(allowed) and set(required) <= set(value))


def single(value):
    require(isinstance(value, list) and len(value) == 1)
    return value[0]


def host(value):
    clean_string(value, 1, 253)
    require("%" not in value)
    try:
        return str(ipaddress.ip_address(value))
    except ValueError:
        require(":" not in value)
        require(not re.fullmatch(r"[0-9.]+", value))
        ascii_name = value.rstrip(".").encode("idna").decode("ascii").lower()
        require(bool(ascii_name) and len(ascii_name) <= 253)
        require(all(re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?", label)
                    for label in ascii_name.split(".")))
        return ascii_name


def port(value):
    require(type(value) is int and 1 <= value <= 65535)
    return value


def decode(value):
    require(not re.search(r"%(?![0-9a-fA-F]{2})", value))
    return clean_string(urllib.parse.unquote(value, encoding="utf-8", errors="strict"), maximum=MAX_INPUT)


def unbase64(value):
    clean_string(value, 1, MAX_INPUT)
    require(bool(re.fullmatch(r"[A-Za-z0-9+/_-]*={0,2}", value)))
    return base64.b64decode(value + "=" * (-len(value) % 4), altchars=b"-_", validate=True)


def query(value):
    if not value:
        return {}
    result = {}
    for part in value.split("&"):
        require(bool(part) and "=" in part)
        key, val = part.split("=", 1)
        key, val = decode(key.replace("+", " ")), decode(val.replace("+", " "))
        require(key not in result)
        result[key] = val
    return result


def reality(params):
    server = host(params.get("sni", ""))
    public = clean_string(params.get("pbk", ""), 43, 44)
    require(len(unbase64(public)) == 32)
    short = clean_string(params.get("sid", ""), 0, 16)
    require(len(short) % 2 == 0 and bool(re.fullmatch(r"[0-9a-fA-F]*", short)))
    fingerprint = params.get("fp", "chrome")
    require(fingerprint in FINGERPRINTS)
    spider = clean_string(params.get("spx", "/"), 1, 1024)
    require(spider.startswith("/"))
    settings = {"serverName": server, "fingerprint": fingerprint,
                "publicKey": public, "shortId": short.lower(), "spiderX": spider}
    if params.get("mldsa65Verify"):
        verify = clean_string(params["mldsa65Verify"], 1, 10000)
        unbase64(verify)
        settings["mldsa65Verify"] = verify
    return settings


def encryption(value):
    clean_string(value, 1, 12000)
    require(value == "none" or bool(re.fullmatch(r"mlkem768x25519plus\.[A-Za-z0-9._+/-]+", value)))
    return value


def xhttp(params):
    path = clean_string(params.get("path", "/"), 1, 4096)
    require(path.startswith("/") and "#" not in path)
    mode = params.get("mode", "auto")
    require(mode in {"auto", "packet-up", "stream-up", "stream-one"})
    http_host = params.get("host", "")
    if http_host:
        http_host = host(http_host)
    settings = {"host": http_host, "path": path, "mode": mode}
    if params.get("extra"):
        extra = json.loads(params["extra"], object_pairs_hook=unique_object)
        validate_obfs(extra)
        if extra:
            settings["extra"] = extra
    return settings


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result)
        result[key] = value
    return result


def validate_obfs(value):
    keys(value, OBFS_FIELDS)
    for key, val in value.items():
        if key == "xPaddingObfsMode":
            require(type(val) is bool)
        else:
            clean_string(val, 1, 256)


def parse_link(link):
    clean_string(link, 1, MAX_INPUT)
    require(not any(c.isspace() for c in link))
    # Legacy Shadowsocks clients encode the entire method:password@endpoint.
    # Decode that form before URL splitting, since standard Base64 may use '/'.
    if link.lower().startswith("ss://"):
        body, separator, remark = link[5:].partition("#")
        if "@" not in body:
            require("?" not in body)
            decoded = clean_string(unbase64(body).decode("utf-8", errors="strict"), 1, MAX_INPUT)
            credential, endpoint = decoded.rsplit("@", 1)
            link = "ss://" + urllib.parse.quote(credential, safe=":") + "@" + endpoint
            if separator:
                link += "#" + remark
    parsed = urllib.parse.urlsplit(link)
    scheme = parsed.scheme.lower()
    require(scheme in {"vless", "trojan", "hysteria2", "hy2", "ss"})
    require(parsed.netloc.count("@") == 1)
    credential_raw, endpoint = parsed.netloc.rsplit("@", 1)
    credential = decode(credential_raw)
    address = host(parsed.hostname or "")
    remote_port = port(parsed.port)
    params = query(parsed.query)
    name = decode(parsed.fragment) if parsed.fragment else f"{scheme}-{address}"
    clean_string(name, 1, 128)
    require(parsed.path in {"", "/"})
    stream = None
    if scheme in {"vless", "trojan"}:
        transport = params.get("type", "tcp")
        if transport == "tcp":
            transport = "raw"
        require(transport in {"raw", "xhttp", "kcp"})
        security = params.get("security", "none")
        if transport == "kcp":
            require(scheme == "vless" and security == "none")
            require(set(params) <= {"type", "security", "seed", "headerType", "encryption"})
            require(params.get("headerType", "none") == "none")
            seed = clean_string(params.get("seed", ""), 1, 4096)
            stream = {"network": "kcp", "security": "none",
                      "kcpSettings": {"uplinkCapacity": 100, "downlinkCapacity": 100,
                                      "congestion": True, "readBufferSize": 5, "writeBufferSize": 5},
                      "finalmask": {"udp": [{"type": "mkcp-legacy", "settings": {"value": seed}}]}}
        else:
            require(security == "reality")
            require(scheme != "trojan" or transport == "xhttp")
            allowed = {"type", "security", "sni", "pbk", "sid", "spx", "fp", "mldsa65Verify"}
            allowed |= {"flow", "encryption"} if scheme == "vless" else set()
            if transport == "xhttp":
                allowed |= {"path", "host", "mode", "extra"}
            require(set(params) <= allowed)
            stream = {"network": transport, "security": "reality", "realitySettings": reality(params)}
            if transport == "xhttp":
                require(not params.get("flow"))
                stream["xhttpSettings"] = xhttp(params)
        if scheme == "vless":
            require(bool(re.fullmatch(r"[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}", credential)))
            user = {"id": str(uuid.UUID(credential)), "encryption": encryption(params.get("encryption", "none"))}
            flow = params.get("flow", "")
            require(flow in {"", "xtls-rprx-vision", "xtls-rprx-vision-udp443"})
            if flow:
                require(transport == "raw")
                user["flow"] = flow
            settings = {"vnext": [{"address": address, "port": remote_port, "users": [user]}]}
            protocol = "vless"
        else:
            clean_string(credential, 1, 4096)
            settings = {"servers": [{"address": address, "port": remote_port, "password": credential}]}
            protocol = "trojan"
    elif scheme in {"hy2", "hysteria2"}:
        require(set(params) <= {"insecure", "sni", "alpn"})
        require(params.get("insecure", "0") == "0" and params.get("alpn", "h3") == "h3")
        clean_string(credential, 1, 4096)
        tls = {"serverName": host(params.get("sni", address)), "alpn": ["h3"]}
        settings = {"version": 2, "address": address, "port": remote_port}
        stream = {"network": "hysteria", "security": "tls", "tlsSettings": tls,
                  "hysteriaSettings": {"version": 2, "auth": credential, "udpIdleTimeout": 60}}
        protocol = "hysteria"
    else:
        require(not params)
        if ":" not in credential:
            credential = unbase64(credential).decode("utf-8", errors="strict")
        method, password = credential.split(":", 1)
        require(method == "2022-blake3-aes-256-gcm")
        require(len(unbase64(password)) == 32)
        settings = {"servers": [{"address": address, "port": remote_port,
                                  "method": method, "password": password}]}
        protocol = "shadowsocks"
    outbound = {"protocol": protocol, "settings": settings}
    if stream is not None:
        outbound["streamSettings"] = stream
    node = {"name": name, "address": address, "port": remote_port, "protocol": protocol, "outbound": outbound}
    validate_node(node)
    return node


def validate_node(node):
    keys(node, {"id", "name", "address", "port", "protocol", "outbound"},
         {"name", "address", "port", "protocol", "outbound"})
    if "id" in node:
        require(bool(re.fullmatch(r"[A-Za-z0-9_-]{1,64}", node["id"])))
    clean_string(node["name"], 1, 128)
    address, remote_port = host(node["address"]), port(node["port"])
    require(address == node["address"])
    outbound = node["outbound"]
    keys(outbound, {"protocol", "settings", "streamSettings"}, {"protocol", "settings"})
    protocol = outbound["protocol"]
    require(protocol == node["protocol"] and protocol in {"vless", "trojan", "hysteria", "shadowsocks"})
    settings = outbound["settings"]
    if protocol == "vless":
        keys(settings, {"vnext"}, {"vnext"})
        server = single(settings["vnext"])
        keys(server, {"address", "port", "users"}, {"address", "port", "users"})
        user = single(server["users"])
        keys(user, {"id", "encryption", "flow"}, {"id", "encryption"})
        require(str(uuid.UUID(user["id"])) == user["id"])
        encryption(user["encryption"])
    elif protocol in {"trojan", "shadowsocks"}:
        keys(settings, {"servers"}, {"servers"})
        server = single(settings["servers"])
        if protocol == "trojan":
            keys(server, {"address", "port", "password"}, {"address", "port", "password"})
            clean_string(server["password"], 1, 4096)
        else:
            keys(server, {"address", "port", "method", "password"}, {"address", "port", "method", "password"})
            require(server["method"] == "2022-blake3-aes-256-gcm" and len(unbase64(server["password"])) == 32)
    else:
        keys(settings, {"version", "address", "port"}, {"version", "address", "port"})
        require(type(settings["version"]) is int and settings["version"] == 2)
        server = settings
    require(server["address"] == address and server["port"] == remote_port and type(server["port"]) is int)
    stream = outbound.get("streamSettings")
    if protocol == "shadowsocks":
        require(stream is None)
        return node
    require(isinstance(stream, dict))
    network, security = stream.get("network"), stream.get("security")
    if protocol == "hysteria":
        keys(stream, {"network", "security", "tlsSettings", "hysteriaSettings"},
             {"network", "security", "tlsSettings", "hysteriaSettings"})
        require(network == "hysteria" and security == "tls")
        tls = stream["tlsSettings"]
        keys(tls, {"serverName", "alpn"}, {"serverName", "alpn"})
        require(tls["serverName"] == host(tls["serverName"]) and tls["alpn"] == ["h3"])
        hy = stream["hysteriaSettings"]
        keys(hy, {"version", "auth", "udpIdleTimeout"}, {"version", "auth", "udpIdleTimeout"})
        require(type(hy["version"]) is int and hy["version"] == 2)
        require(type(hy["udpIdleTimeout"]) is int and hy["udpIdleTimeout"] == 60)
        clean_string(hy["auth"], 1, 4096)
    elif network == "kcp":
        keys(stream, {"network", "security", "kcpSettings", "finalmask"},
             {"network", "security", "kcpSettings", "finalmask"})
        require(protocol == "vless" and security == "none" and not user.get("flow"))
        require(stream["kcpSettings"] == {"uplinkCapacity": 100, "downlinkCapacity": 100,
                "congestion": True, "readBufferSize": 5, "writeBufferSize": 5})
        mask = stream["finalmask"]
        keys(mask, {"udp"}, {"udp"})
        mask = single(mask["udp"])
        keys(mask, {"type", "settings"}, {"type", "settings"})
        require(mask["type"] == "mkcp-legacy")
        keys(mask["settings"], {"value"}, {"value"})
        clean_string(mask["settings"]["value"], 1, 4096)
    else:
        require(network in {"raw", "xhttp"} and security == "reality")
        require(protocol != "trojan" or network == "xhttp")
        allowed = {"network", "security", "realitySettings"} | ({"xhttpSettings"} if network == "xhttp" else set())
        keys(stream, allowed, allowed)
        rs = stream["realitySettings"]
        required = {"serverName", "fingerprint", "publicKey", "shortId", "spiderX"}
        keys(rs, required | {"mldsa65Verify"}, required)
        params = {"sni": rs["serverName"], "fp": rs["fingerprint"], "pbk": rs["publicKey"],
                  "sid": rs["shortId"], "spx": rs["spiderX"]}
        if "mldsa65Verify" in rs:
            params["mldsa65Verify"] = rs["mldsa65Verify"]
        require(rs == reality(params))
        if protocol == "vless":
            flow = user.get("flow", "")
            require(flow in {"", "xtls-rprx-vision", "xtls-rprx-vision-udp443"})
            require(not flow or network == "raw")
        if network == "xhttp":
            xs = stream["xhttpSettings"]
            keys(xs, {"host", "path", "mode", "extra"}, {"host", "path", "mode"})
            params = {k: xs[k] for k in ("host", "path", "mode")}
            if "extra" in xs:
                params["extra"] = json.dumps(xs["extra"])
            require(xs == xhttp(params))
    return node


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--validate-node", action="store_true")
    args = parser.parse_args()
    try:
        raw = sys.stdin.read(MAX_INPUT + 1)
        require(len(raw) <= MAX_INPUT)
        if args.validate_node:
            node = validate_node(json.loads(raw, object_pairs_hook=unique_object))
        else:
            # A single trailing newline is conventional stdin framing, not URI content.
            node = parse_link(raw.rstrip("\r\n"))
        print(json.dumps(node, ensure_ascii=False, separators=(",", ":")))
    except (InvalidLink, ValueError, TypeError, KeyError, AttributeError, UnicodeError, binascii.Error, RecursionError):
        print("Unsupported or invalid relay share link/node. Check protocol, transport and required parameters.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
