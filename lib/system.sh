#!/usr/bin/env bash
# =============================================================================
# 文件名称: system.sh
# 功能描述: 系统探测层——发行版识别与命令存在性检查的唯一实现。
#           只定义 cmd_exists / _os / _os_full / _os_ver，
#           不定义颜色、PATH 等常量，因此 core/*.sh（经 lib/common.sh）与
#           可独立执行的 service/*.sh 都能安全 source，不会触发 readonly 冲突。
# 依赖: 无
# =============================================================================

[[ -n "${_SYSTEM_SH_LOADED:-}" ]] && return 0
readonly _SYSTEM_SH_LOADED=1

# =============================================================================
# 函数名称: cmd_exists
# 功能描述: 检查指定的命令是否存在于系统中。
# 参数:
#   $1: 要检查的命令名称
# 返回值: 0-命令存在 1-命令不存在 (由命令检查工具的退出码决定)
# =============================================================================
function cmd_exists() {
    command -v "$1" >/dev/null 2>&1
}

# =============================================================================
# 函数名称: _os
# 功能描述: 检测当前操作系统的发行版名称。
# 参数: 无
# 返回值: 操作系统名称 (echo 输出: debian/ubuntu/centos/...)
# =============================================================================
function _os() {
    local os=""
    if [[ -f "/etc/debian_version" ]]; then
        source /etc/os-release && os="${ID}"
        printf -- "%s" "${os}" && return
    fi
    if [[ -f "/etc/redhat-release" ]]; then
        os="centos"
        printf -- "%s" "${os}" && return
    fi
}

# =============================================================================
# 函数名称: _os_full
# 功能描述: 获取当前操作系统的完整发行版信息。
# 参数: 无
# 返回值: 完整的操作系统版本信息 (echo 输出)
# =============================================================================
function _os_full() {
    if [[ -f /etc/redhat-release ]]; then
        awk '{print ($1,$3~/^[0-9]/?$3:$4)}' /etc/redhat-release && return
    fi
    if [[ -f /etc/os-release ]]; then
        awk -F'[= "]' '/PRETTY_NAME/{print $3,$4,$5}' /etc/os-release && return
    fi
    if [[ -f /etc/lsb-release ]]; then
        awk -F'[="]+' '/DESCRIPTION/{print $2}' /etc/lsb-release && return
    fi
}

# =============================================================================
# 函数名称: _os_ver
# 功能描述: 获取当前操作系统的主版本号。
# 参数: 无
# 返回值: 操作系统的主版本号 (echo 输出)
# =============================================================================
function _os_ver() {
    local main_ver
    main_ver="$(_os_full | grep -oE '[0-9.]+')"
    printf -- "%s" "${main_ver%%.*}"
}
